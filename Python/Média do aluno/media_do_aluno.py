# Solicita ao usuário a nota da prova 1 e 2.
n1 = float(input("Digite a nota da prova 1: "))
n2 = float(input("Digite a nota da prova 2: "))

# Faz o calculo da média e arrendonda seu valor.
media = (n1 + n2) / 2
media = round(media, 1)
print(f"\nMédia: {media}")

# Define o status do usuário: Aprovado ou Reprovado.
status = ""
if media >= 6:
  status = "Aprovado"
else:
  status = "Reprovado"
print(f"Status: {status}")