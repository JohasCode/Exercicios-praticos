import sqlite3

class Banco:
    # Conexão com banco de dados
    def __init__(self, banco):
        self.conn = sqlite3.connect(banco)
        self.criar_tabelas()

    # Criar a tabela Estoque e Movimentação se não existir
    def criar_tabelas(self):
        cursor = self.conn.cursor()
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS Estoque (
                id_estoque INTEGER PRIMARY KEY,
                nome TEXT NOT NULL,
                categoria TEXT NOT NULL,
                quantidade INTEGER,
                preco REAL NOT NULL,
                localizacao TEXT
            )
            CREATE TABLE IF NOT EXISTS Movimentacao (
                id_produto INTEGER NOT NULL,
                tipo TEXT NOT NULL,
                quantidade INTEGER
            )
        """)
        self.conn.commit()

    # Adicionar um produto a tabela Estoque
    def cadastrar_produto(self, nome, categoria, quantidade, preco, localizacao):
        cursor = self.conn.cursor()
        cursor.execute(
            "INSERT INTO Estoque (nome, categoria, quantidade, preco, localizacao) VALUES (?, ?, ?, ?, ?)", (nome, categoria, quantidade, preco, localizacao)
        )
        self.conn.commit()
        print(f"[+] Produto cadastrado com sucesso: {nome}, {categoria}, {quantidade}, R${preco}, {localizacao}")

    # Registrar movimentação de entrada do produto
    def registrar_entrada(self, id, quantidade):
        cursor = self.conn.cursor()
        cursor.execute(
            "SELECT quantidade FROM Estoque WHERE id_estoque = ?", (id,))
        resultado = cursor.fetchone()
        if resultado:
            estoque_atual = resultado[0]
            cursor.execute(
                "UPDATE Estoque SET quantidade = ? WHERE id_estoque = ?", (estoque_atual + quantidade, id))
            cursor.execute(
                "INSERT INTO Movimentacao (id_produto, tipo, quantidade) VALUES (?, 'entrada', ?)", (id, quantidade))
            self.conn.commit()
            print(f"[+] Entrada de {quantidade} ao produto {id} com sucesso.")
        else:
            print(f"[!] Produto {id} não encontrado em estoque.")

    # Registrar movimentação de saída do produto (como venda, etc)
    def registrar_saida(self, id, quantidade):
        cursor = self.conn.cursor()
        cursor.execute(
            "SELECT quantidade FROM Estoque WHERE id_estoque = ?", (id,))
        resultado = cursor.fetchone()
        if resultado:
            estoque_atual = resultado[0]
            if estoque_atual < quantidade:
                print(f"[!] Estoque insuficiente: Quantidade a sair excede a quantidade em estoque.")
            else:
                cursor.execute(
                    "UPDATE Estoque SET quantidade = ? WHERE id_estoque = ?", (estoque_atual - quantidade, id))
                cursor.execute(
                    "INSERT INTO Movimentacao (id_produto, tipo, quantidade) VALUES (?, 'saida', ?)", (id, quantidade))
                self.conn.commit()
                print(f"[-] Saída de {quantidade} do produto {id} com sucesso.")
        else:
            print(f"[!] Produto {id} não encontrado em estoque.")

    # Gerar o relatorio do estoque
    def gerar_relatorio_estoque(self):
        cursor = self.conn.cursor()
        cursor.execute(
            "SELECT * FROM Estoque")
        produtos = cursor.fetchone()
        print("\nRelatório do estoque:")
        for produto in produtos:
            print(produto)

    # Consultar o historico de movimentação do estoque
    def consultar_historico(self):
        cursor = self.conn.cursor()
        cursor.execute(
            "SELECT * FROM Movimentacao")
        movimentacoes = cursor.fetchone()
        print("\nHistorico de movimentação:")
        for movimentacao in movimentacoes:
            print(movimentacao)



    # EXTRAS --

    # Atualizar a quantidade e preco de um produto
    def atualizar_produto(self, nome, quantidade, preco):
        cursor = self.conn.cursor()
        cursor.execute(
            "SELECT * FROM Estoque WHERE nome = ?", (nome,))
        resultado = cursor.fetchone()
        if resultado > 0:
            cursor.execute(
                "UPDATE Estoque SET quantidade = ?, preco = ? WHERE nome = ?", (quantidade, preco, nome))
            self.conn.commit()
            print(f"Produto atualizado com sucesso: {nome}, {quantidade}, R${preco}")
        else:
            print(f"[!] {nome} não encontrado.")

    # Deletar um produto da tabela Estoque
    def excluir_produto(self, id):
        cursor = self.conn.cursor()
        cursor.execute(
            "DELETE Estoque WHERE id_estoque = ?", id)
        self.conn.commit()
        print("[-] Produto excluído com sucesso.")

    # Listar todos os produtos
    def listar_produto(self):
        cursor = self.conn.cursor()
        cursor.execute("SELECT * FROM Estoque")
        produtos = cursor.fetchall()
        return [produto[0] for produto in produtos]