# Sistema: Cálculo de IMC

# Solicita ao usuário que insira o valor do Peso e Altura.
peso = float(input("Digite o seu peso (em quilogramas): "))
altura = float(input("Digite a sua altura (em metros): "))

# Faz o cálculo de IMC e arredonda o resultado.
imc = peso / (altura * altura)
imc = round(imc, 1)

# Exibe o resultado do IMC.
print(f"\nSeu IMC é {str(imc)}")

# Classifica o IMC.
if imc < 18.5:
  print("Você está abaixo do peso!")
elif 18.5 <= imc < 24.9:
  print("Você está com peso ideal!")
elif 25.0 <= imc < 29.9:
  print("Você está com sobrepeso!")
elif 30.0 <= imc < 34.9:
  print("Você está com obesidade (grau I)!")
elif 35.0 <= imc < 39.9:
  print("Você está com obesidade severa (grau II)!")
else:
  print("Você está com obesidade mórbida (grau III)!")